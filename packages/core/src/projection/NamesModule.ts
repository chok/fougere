import { basesOf, realizationsOf } from '../descriptor/bases.js';
import type { FrondDescriptor } from '../descriptor/FrondDescriptor.js';
import type { ScanResult } from '../scan.js';

function union(names: Iterable<string>): string {
  const all = [...new Set(names)].sort();

  return all.length > 0 ? all.map((name) => `'${name}'`).join(' | ') : 'never';
}

function declaredIn(frond: FrondDescriptor): Set<string> {
  return new Set([
    ...frond.providers.map((one) => one.ctor.name),
    ...frond.handlers.map((one) => one.ctor.name),
  ]);
}

/** Where the names sit, from the project's root: `include` of `@fougere/core/tsconfig` reads them there, beside the config. */
export const NAMES = '.fougere/names.generated.d.ts';

export function emitNames(scan: ScanResult): string {
  const fronds = new Set<string>();
  const entities = new Set<string>();
  const handlers = new Set<string>();
  const providers = new Set<string>();
  const ports = new Map<string, Set<string>>();

  for (const frond of scan.fronds) {
    fronds.add(frond.name);
    for (const entity of frond.entities) {
      entities.add(entity.name);
      entities.add(entity.entityClass.name);
    }
    for (const handler of frond.handlers) handlers.add(handler.ctor.name);
    for (const provider of frond.providers) providers.add(provider.ctor.name);

    const declared = declaredIn(frond);
    for (const [port, answering] of basesOf([...frond.providers, ...realizationsOf(frond)], (name) => declared.has(name))) {
      const known = ports.get(port) ?? new Set<string>();
      for (const one of answering) known.add(one.ctor.name);
      ports.set(port, known);
    }
  }

  return [
    '// Generated by Fougere from what the scan found — do not edit, and do not commit.',
    '// Rewritten whenever the app boots, so it cannot drift from the project it was read off.',
    '',
    "declare module '@fougere/core' {",
    '  /** Every name this project declares, by kind. A config may write no other. */',
    '  interface FougereNames {',
    `    frond: ${union(fronds)};`,
    `    entity: ${union(entities)};`,
    `    handler: ${union(handlers)};`,
    `    provider: ${union(providers)};`,
    '  }',
    '',
    '  /** Each port, and what extends it — so a config cannot answer one with the other. */',
    '  interface FougerePorts {',
    ...(ports.size > 0
      ? [...ports].sort().map(([port, answering]) => `    ${memberOf(port)}: ${union(answering)};`)
      : ['    // This project declares no port.']),
    '  }',
    '}',
    '',
    'export {};',
    '',
  ].join('\n');
}

function memberOf(port: string): string {
  return /^[A-Za-z_$][\w$]*$/.test(port) ? port : `'${port}'`;
}
